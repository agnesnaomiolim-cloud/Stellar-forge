"""Generate platform-independent notices from Cargo's locked dependency graph."""

import argparse
import difflib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
HEADER = """# Third-Party Licenses

This project depends on a number of open-source libraries.
Their names, versions, authors, and license identifiers are listed below.

> This file is auto-generated by `scripts/generate-third-party-licenses.py`.
> Run `make third-party-licenses` to regenerate after updating `Cargo.toml`.
> Run `make check-third-party-licenses` to verify this file in CI/local checks.

| Crate | Version | License | Authors |
|-------|---------|---------|---------|
"""


def render(metadata):
    """Include runtime dependencies across all targets, excluding build/dev edges."""
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    pending = [metadata["resolve"]["root"]]
    included = set()
    while pending:
        package_id = pending.pop()
        if package_id in included:
            continue
        included.add(package_id)
        for dependency in nodes[package_id]["deps"]:
            if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                pending.append(dependency["pkg"])

    def escape(value):
        return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ")

    rows = []
    for package in metadata["packages"]:
        if package["id"] not in included:
            continue
        columns = (
            package["name"], package["version"],
            package.get("license") or "(see crate)",
            "|".join(package["authors"]),
        )
        rows.append("| " + " | ".join(map(escape, columns)) + " |\n")
    return HEADER + "".join(sorted(rows, key=str.casefold))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--features",
         "rest-api,metrics,admission-webhook,k8s-v1-30"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    generated = render(json.loads(result.stdout))
    if args.check:
        previous = OUTPUT.read_text(encoding="utf-8")
        if previous != generated:
            print("".join(difflib.unified_diff(
                previous.splitlines(True), generated.splitlines(True),
                fromfile=str(OUTPUT), tofile="generated notices",
            )))
            raise SystemExit(1)
        print("Third-party license references are up to date")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.name}")


if __name__ == "__main__":
    main()
